"""Policy genomes in the learner's closed grammar (admit / resolve / ttl / promote), rendered as policy files.

The learner in aura/server.aura rewrites exactly these four defines from its rule tables; a genome here is
the same rule set written as data, so every candidate is a policy the learner itself could have kept.
Nothing here proposes or searches: the candidate list is the domain input to std/evo-core's ask/tell and
std/proposer's EoH-S set selection.
"""
from __future__ import annotations

import json

CATS = ("pref", "fact", "project", "episodic")
MODES = ("keep-first", "latest", "keep-both")


def genome(admit=None, resolve=None, ttl=None, promote=None, note="") -> dict:
    return {"admit": admit or [], "resolve": resolve or {}, "ttl": ttl or {}, "promote": promote or {},
            "note": note}


def genome_id(g: dict) -> str:
    return json.dumps({k: g[k] for k in ("admit", "resolve", "ttl", "promote")},
                      sort_keys=True, separators=(",", ":"))


def source(g: dict, version: int = 0) -> str:
    """Render the five policy defines. Rule values are literals, so the file is a plain policy the server
    loads with set-code + eval-current."""
    admit_rows = []
    for (c, s, v) in g["admit"]:
        admit_rows.append((c, s, "#t" if v else "#f"))
    # the default is the seed's "only the user is admitted"; a genome adds/overrides (cat, src) rules
    adm = ("\n".join(f"          ((and (equal? cat {json.dumps(c)}) (equal? src {json.dumps(s)})) {v})"
                     for (c, s, v) in admit_rows) + '\n          (else (equal? src "user"))')
    def cat_cond(mapping, default):
        rows = "\n".join(f"          ((equal? cat {json.dumps(c)}) {json.dumps(v)})"
                          for c, v in mapping.items())
        return (rows + f"\n          (else {default})") if rows else f"          (else {default})"
    resolve_map = {c: g["resolve"].get(c, "keep-first" if c in ("pref", "fact") else "latest")
                   for c in CATS}
    ttl_map = {c: g["ttl"][c] for c in CATS if c in g["ttl"]}
    promote_map = {c: g["promote"][c] for c in CATS if c in g["promote"]}
    return f""";; aura-memory policy v{version} (generated by aura_memory/policy_gen.py from a rule genome)
;; {g.get("note", "")}
(define admit
  (lambda (cat src)
    (cond
{adm})))

(define resolve
  (lambda (cat)
    (cond
{cat_cond(resolve_map, chr(34) + "latest" + chr(34))})))

(define ttl
  (lambda (cat)
    (cond
{cat_cond(ttl_map, "0")})))

(define promote-at
  (lambda (cat)
    (cond
{cat_cond(promote_map, "2")})))

(define src-weight
  (lambda (src)
    (cond ((equal? src "correction") 3)
          ((equal? src "user") 3)
          ((equal? src "teammate") 1)
          ((equal? src "assistant") 1)
          (else 0))))
"""


def seed_genome() -> dict:
    return genome(resolve={"pref": "keep-first", "fact": "keep-first"}, note="seed (fixed white-box)")


def family() -> list[dict]:
    """The learner's own mutation vocabulary, composed: the three KEEPs every stream finds
    (resolve pref latest, ttl episodic 60, admit project teammate) plus their neighbours."""
    L = {"pref": "latest"}
    T = lambda n: {"episodic": n}
    P = [("project", "teammate", True)]
    A = [("pref", "assistant", True)]
    return [
        genome(note="seed"),
        genome(resolve=L, note="resolve pref latest"),
        genome(resolve=L, ttl=T(60), note="learner KEEP trio, ttl 60"),
        genome(resolve=L, ttl=T(60), admit=P, note="trio (seed0-4 final)"),
        genome(resolve=L, ttl=T(120), admit=P, note="trio, ttl 120"),
        genome(resolve=L, ttl=T(240), admit=P, note="trio, ttl 240"),
        genome(resolve=L, ttl=T(0), admit=P, note="trio, no ttl"),
        genome(resolve={"pref": "keep-both", "fact": "keep-first"}, ttl=T(120), admit=P,
               note="keep-both prefs, ttl 120"),
        genome(resolve=L, ttl=T(120), admit=P, promote={"episodic": 1}, note="ttl 120, promote 1"),
        genome(resolve=L, ttl=T(120), admit=P, promote={"episodic": 3}, note="ttl 120, promote 3"),
        genome(resolve=L, ttl=T(60), admit=P + A, note="trio + assistant-pref (gate-rejected)"),
        genome(resolve={"pref": "latest", "fact": "latest", "project": "keep-first"}, ttl=T(120),
               admit=P, note="resolve project keep-first"),
        genome(ttl=T(120), admit=P, note="shift-only fix, ttl 120"),
        genome(resolve=L, ttl={"episodic": 120, "pref": 300}, admit=P, note="ttl pref 300 too"),
        genome(resolve=L, ttl=T(60), admit=P + [("project", "user", True)],
               note="trio, project user admitted"),
        genome(resolve={"pref": "latest", "fact": "latest"}, ttl=T(60), admit=P,
               note="trio, latest facts too"),
        genome(resolve=L, ttl=T(20), admit=P, note="compaction probe, ttl 20"),
        genome(resolve=L, ttl=T(30), admit=P, note="compaction probe, ttl 30"),
        genome(resolve=L, ttl=T(60), admit=P, promote={"episodic": 1}, note="ttl 60, promote 1"),
        genome(resolve={"pref": "keep-both", "fact": "keep-first"}, ttl=T(60), admit=P,
               note="keep-both prefs, ttl 60"),
    ]
